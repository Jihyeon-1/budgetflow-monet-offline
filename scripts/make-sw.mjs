import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';

const root = 'dist';
async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir,{withFileTypes:true})) {
    const path = join(dir,e.name);
    if (e.isDirectory()) out.push(...await walk(path));
    else if (e.isFile() && e.name !== 'sw.js') out.push(relative(root,path).split(sep).join('/'));
  }
  return out;
}
const files = await walk(root);
const hash = createHash('sha256');
for (const file of files.sort()) { hash.update(file); hash.update(await readFile(join(root,file))); }
const version = hash.digest('hex').slice(0,14);
const contents = `/* BudgetFlow Offline - generated by scripts/make-sw.mjs */
const CACHE = 'budgetflow-offline-${version}';
const ASSETS = ${JSON.stringify(['./',...files.map(x=>'./'+x)])};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache)=>cache.addAll(ASSETS)).then(()=>self.skipWaiting()));
});
self.addEventListener('activate',(event)=>{
  event.waitUntil(caches.keys().then((names)=>Promise.all(names.filter((name)=>name.startsWith('budgetflow-offline-') && name!==CACHE).map((name)=>caches.delete(name)))).then(()=>self.clients.claim()));
});
self.addEventListener('fetch',(event)=>{
  if (event.request.method!=='GET') return;
  const url=new URL(event.request.url);
  if (url.origin!==self.location.origin) return;
  if (event.request.mode==='navigate') {
    event.respondWith(fetch(event.request).then((r)=>{
      if(r.ok) { const copy=r.clone(); caches.open(CACHE).then(c=>c.put(event.request,copy)); }
      return r;
    }).catch(()=>caches.match(event.request).then((r)=>r || caches.match('./'))));
    return;
  }
  event.respondWith(caches.match(event.request).then((cached)=>cached || fetch(event.request).then((r)=>{
    if(r.ok && url.pathname.startsWith(new URL('./',self.registration.scope).pathname)) {
      const copy=r.clone(); caches.open(CACHE).then(c=>c.put(event.request,copy));
    }
    return r;
  })));
});
`;
await writeFile(join(root,'sw.js'),contents);
console.log(`Offline service worker written (${files.length} assets, cache ${version})`);
